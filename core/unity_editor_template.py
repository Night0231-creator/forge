"""Unity 2021 Editor helper: auto-generate Astronyx preview materials and prefabs.

This script is opt-in and copied ONLY to the user's explicitly selected
TaleWeaverLite Unity project's Assets/Editor folder. It does not invoke the
private TaleWeaverLite Save or .tsMod export API.
"""
UNITY_EDITOR_CS = r'''// Astronyx Mini Forge V2.2.13 - optional Unity editor integration
// Generates preview prefabs/materials from explicitly imported Meshy models.
// It does NOT export TaleSpire .tsMod, alter Default Scale, or change project settings.
#if UNITY_EDITOR
using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

[InitializeOnLoad]
public static class AstronyxMiniForgeBridgeV2213
{
    private const string Root = "Assets/AstronyxImports";

    static AstronyxMiniForgeBridgeV2213()
    {
        EditorApplication.delayCall += PrepareAll;
    }

    [MenuItem("Tools/Astronyx/Preparar modelos importados")]
    public static void PrepareAll()
    {
        string absolute = Path.Combine(Application.dataPath, "AstronyxImports");
        if (!Directory.Exists(absolute)) return;
        foreach (string directory in Directory.GetDirectories(absolute))
        {
            string token = Path.GetFileName(directory);
            if (string.IsNullOrEmpty(token)) continue;
            // Path tokens are generated by the Mini Forge; do not follow links.
            string folder = Root + "/" + token;
            string modelPath = folder + "/Model_PivoPes.obj";
            string prefabPath = folder + "/Astronyx_Preview.prefab";
            if (AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath) != null) continue;
            if (!File.Exists(Path.Combine(directory, "Model_PivoPes.obj"))) continue;
            try
            {
                BuildPrefab(folder, modelPath, prefabPath);
            }
            catch (Exception ex)
            {
                Debug.LogError("[Astronyx] Falha ao preparar " + token + ": " + ex);
            }
        }
    }

    private static void BuildPrefab(string folder, string modelPath, string prefabPath)
    {
        Mesh mesh = AssetDatabase.LoadAllAssetsAtPath(modelPath)
            .OfType<Mesh>()
            .OrderByDescending(m => m.vertexCount)
            .FirstOrDefault();
        if (mesh == null) return; // Unity may still be importing this OBJ.
        string matPath = folder + "/Astronyx_Visual.mat";
        Material material = AssetDatabase.LoadAssetAtPath<Material>(matPath);
        if (material == null)
        {
            Shader shader = Shader.Find("Standard");
            if (shader == null) shader = Shader.Find("Unlit/Texture");
            if (shader == null) throw new InvalidOperationException("Shader preview ausente");
            material = new Material(shader);
            material.name = "Astronyx_Visual";
            var albedo = AssetDatabase.LoadAssetAtPath<Texture2D>(folder + "/Albedo.png");
            if (albedo != null) material.mainTexture = albedo;
            var importer = AssetImporter.GetAtPath(folder + "/Normal.png") as TextureImporter;
            if (importer != null && importer.textureType != TextureImporterType.NormalMap)
            {
                importer.textureType = TextureImporterType.NormalMap;
                importer.SaveAndReimport();
            }
            var normal = AssetDatabase.LoadAssetAtPath<Texture2D>(folder + "/Normal.png");
            if (normal != null && material.HasProperty("_BumpMap"))
            {
                material.SetTexture("_BumpMap", normal);
                material.EnableKeyword("_NORMALMAP");
            }
            // MAES texture is retained for assignment in TaleWeaverLite.
            // It is NOT interchangeable with Standard shader's metallic texture.
            AssetDatabase.CreateAsset(material, matPath);
        }
        var root = new GameObject("Astronyx_1x1_Preview");
        try
        {
            var visual = new GameObject("Visual_Mesh");
            visual.transform.SetParent(root.transform, false);
            visual.transform.localScale = Vector3.one; // no arbitrary 8x
            visual.AddComponent<MeshFilter>().sharedMesh = mesh;
            visual.AddComponent<MeshRenderer>().sharedMaterial = material;
            PrefabUtility.SaveAsPrefabAsset(root, prefabPath);
        }
        finally
        {
            UnityEngine.Object.DestroyImmediate(root);
        }
        Debug.Log("[Astronyx] Prefab pronto: " + prefabPath +
                  " (1x visual de origem, sem configurar escala do jogo).");
    }
}

public sealed class AstronyxMiniForgeImportWatcherV2213 : AssetPostprocessor
{
    static void OnPostprocessAllAssets(
        string[] importedAssets, string[] deletedAssets,
        string[] movedAssets, string[] movedFromAssetPaths)
    {
        if (importedAssets.Any(path =>
            path.StartsWith("Assets/AstronyxImports/", StringComparison.Ordinal) &&
            path.EndsWith(".obj", StringComparison.OrdinalIgnoreCase)))
        {
            EditorApplication.delayCall += AstronyxMiniForgeBridgeV2213.PrepareAll;
        }
    }
}
#endif
'''
